// Command devstack runs the whole system on this machine without Docker, for
// poking at the API by hand: a throwaway PostgreSQL, the simulated broker in
// auto mode and the OMS with its workers.
//
// SIMULATED / PAPER ONLY. Development use only: the database is deleted on
// exit. Fresh credentials are generated on every start and written to a
// file readable only by you (default .local/credentials.env); they are never
// printed. For anything longer-lived use docker-compose.yml, which runs the
// real binaries (cmd/omsd, cmd/brokersim) against a persistent PostgreSQL.
package main

import (
	"context"
	"flag"
	"fmt"
	"log/slog"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"
	"time"

	"oms/src/brokersim"
	"oms/src/localstack"
	"oms/src/reconcile"
)

func main() {
	addr := flag.String("addr", "127.0.0.1:8080", "OMS listen address")
	brokerAddr := flag.String("broker-addr", "127.0.0.1:9090", "simulated broker listen address")
	creds := flag.String("credentials", ".local/credentials.env", "where to write this run's generated credentials")
	fillDelay := flag.Duration("fill-delay", 500*time.Millisecond, "simulated broker: delay before each fill")
	flag.Parse()

	if err := run(*addr, *brokerAddr, *creds, *fillDelay); err != nil {
		fmt.Fprintln(os.Stderr, "devstack:", err)
		os.Exit(1)
	}
}

func run(addr, brokerAddr, creds string, fillDelay time.Duration) error {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	log := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelInfo}))
	s, err := localstack.Start(ctx, localstack.Options{
		Addr: addr, BrokerAddr: brokerAddr,
		Auto: true, Background: true,
		Reconcile: reconcile.Config{Interval: 30 * time.Second},
		Sim: func(c *brokersim.Config) {
			c.AckDelay, c.FillDelay, c.CancelDelay = 50*time.Millisecond, fillDelay, 50*time.Millisecond
		},
		Log: log,
	})
	if err != nil {
		return err
	}
	defer s.Close()

	if err := os.MkdirAll(filepath.Dir(creds), 0o700); err != nil {
		return err
	}
	content := fmt.Sprintf(`# Generated by devstack for one run. SIMULATED / PAPER ONLY. Do not commit.
OMS_URL=%s
BROKER_URL=%s
TRADER_TOKEN=%s
VIEWER_TOKEN=%s
OPERATOR_TOKEN=%s
OMS_BROKER_API_KEY=%s
`, s.URL, s.BrokerURL, s.Trader, s.Viewer, s.Operator, s.BrokerKey)
	if err := os.WriteFile(creds, []byte(content), 0o600); err != nil {
		return err
	}
	defer os.Remove(creds)

	fmt.Printf(`SIMULATED / PAPER ONLY: no real venue is contacted.
  OMS API           %s
  simulated broker  %s
  credentials       %s   (this run only; deleted on exit)
  principals        alice: trader for ACC-1, ACC-2   vera: viewer for ACC-1   olivia: operator
  symbols           AAPL 150, MSFT 400, TSLA 250, NVDA 900 (limit orders at or through these prices fill)

Try:  scripts/api-walkthrough.sh        Ctrl-C to stop.
`, s.URL, s.BrokerURL, creds)

	<-ctx.Done()
	fmt.Println("\nstopping...")
	return nil
}
